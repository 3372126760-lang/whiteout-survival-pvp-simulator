from pathlib import Path
import json,re,subprocess,hashlib,concurrent.futures
from html import unescape
from PIL import Image
heroes=json.loads(subprocess.check_output(['node','--import','tsx','--input-type=module','-e',"import {EXPEDITION_HERO_DATA} from './src/pvp/heroSkills/data/expeditionHeroes.ts'; console.log(JSON.stringify(EXPEDITION_HERO_DATA.filter(h=>h.rarity!=='SSR')));"],encoding='utf-8'))
slugs=['eugene','smith','charlie','cloris-2','sergey','patrick','bahiti','jessie','seo-yoon','jasser','lumak-bokan','ling-shuang','gina']
out=Path('public/assets/heroes-common');out.mkdir(parents=True,exist_ok=True)
def download(url,p):
 subprocess.run(['curl.exe','-f','-L','--retry','2','-A','Mozilla/5.0','-s',url,'-o',str(p)],check=True)
assets={};skills={};manifest=[]
def process(pair):
 hero,slug=pair;page=f'https://wosgift.com/zh-cn/heroes/{slug}/';cache=Path(f'.tmp/wosgift-{slug}.html');download(page,cache)
 html=cache.read_text(encoding='utf-8');tags=re.findall(r'<img[^>]+>',html)
 portrait=next(re.search(r'src="([^"]+)"',t)[1] for t in tags if re.search(r'src="/images/heroes/[^/".]+\.(png|jpg|webp)"',t))
 skilltags=[t for t in tags if f'/skills/{slug}/' in t][-len(hero['expeditionSkills']):]
 assert len(skilltags)==len(hero['expeditionSkills']),slug
 entries=[];heroassets=[];skillmap={}
 for typ,url,name in [('portrait',portrait,hero['name'])]+[('skill',re.search(r'src="([^"]+)"',t)[1],unescape(re.search(r'alt="([^"]*)"',t)[1])) for t in skilltags]:
  filename=f'{slug}-{Path(url).name}' if typ=='skill' else f'{slug}{Path(url).suffix}'
  dst=out/filename;download('https://wosgift.com'+url,dst);Image.open(dst).verify();path='assets/heroes-common/'+filename
  entries.append({'path':path,'name':name,'source':'https://wosgift.com'+url,'page':page,'sha256':hashlib.sha256(dst.read_bytes()).hexdigest()});heroassets.append(path)
 for skill,entry in zip(hero['expeditionSkills'],entries[1:]):
  skillmap[skill['id']]={'path':entry['path'],'name':skill['name']}
  if skill.get('combatSkillDefinitionId'):skillmap[skill['combatSkillDefinitionId']]={'path':entry['path'],'name':skill['name']}
 return hero['id'],{'portrait':heroassets[0],'skills':heroassets[1:]},skillmap,entries
with concurrent.futures.ThreadPoolExecutor(max_workers=4) as pool:
 for hid,art,sm,entries in pool.map(process,zip(heroes,slugs)):
  assets[hid]=art;skills.update(sm);manifest+=entries
  print(hid,[(e['name']) for e in entries])
(out/'manifest.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2),encoding='utf-8')
Path('src/ui/data/commonHeroArtData.ts').write_text('// R/SR artwork from WosGift, generated by scripts/import-common-hero-art.py.\nexport const COMMON_HERO_ART: Readonly<Record<string, { portrait:string; skills:readonly string[] }>> = '+json.dumps(assets,ensure_ascii=False,indent=2)+';\nexport const COMMON_SKILL_ART: Readonly<Record<string, { path:string; name:string }>> = '+json.dumps(skills,ensure_ascii=False,indent=2)+';\n',encoding='utf-8')
